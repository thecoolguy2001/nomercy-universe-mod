def main():
    out = sys.stdout
    out.write("/* Generated by tools/gen_font.py - do not edit. */\n")
    out.write("#ifndef FONT_H\n#define FONT_H\n#include <stdint.h>\n\n")
    out.write("/* FONT[c - 32][row], bit 4 = leftmost pixel. 0 = blank. */\n")
    out.write("static const uint8_t FONT[96][7] = {\n")
    for code in range(32, 128):
        ch = chr(code)
        g = GLYPHS.get(ch)
        if g is None:
            out.write("    {0},\n")
            continue
        rows = g.split("|")
        assert len(rows) == 7 and all(len(r) == 5 for r in rows), ch
        vals = [sum(1 << (4 - i) for i, p in enumerate(r) if p == "#") for r in rows]
        name = ch.replace("\\", "\\\\").replace("'", "\\'")
        out.write("    {%s}, /* '%s' */\n" % (", ".join("0x%02x" % v for v in vals), name))
    out.write("};\n\n#endif\n")


if __name__ == "__main__":
    main()
